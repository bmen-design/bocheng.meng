#!/usr/bin/env python3
"""Build the portfolio as ordinary HTML, CSS, JavaScript and media in dist/."""

import argparse
import json
import re
import shutil
import tempfile
from pathlib import Path

from render import ROOT, render
from serve import video_parts


MARKER = ".studio-export"
CHUNK = re.compile(r"(.*\.mp4)\.part\d{3}$")


def build(destination, base_path):
    projects = json.loads((ROOT / "content/projects.json").read_text())["projects"]
    routes = {"/": "index.html", "/404": "404.html"}
    for project in projects:
        slug = project["slug"]
        if not re.fullmatch(r"[a-zA-Z0-9_-]+", slug):
            raise ValueError(f"Unsupported project slug: {slug!r}")
        routes[f"/work/{slug}"] = f"work/{slug}/index.html"

    for route, name in routes.items():
        status, html = render(route, base_path)
        if status != (404 if route == "/404" else 200):
            raise ValueError(f"Unable to render {route}")
        target = destination / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(html, encoding="utf-8")

    shutil.copytree(ROOT / "assets", destination / "assets",
                    ignore=shutil.ignore_patterns(".DS_Store"))
    media = ROOT / "media"
    if media.is_dir():
        shutil.copytree(media, destination / "media",
                    ignore=shutil.ignore_patterns("*.mp4.part[0-9][0-9][0-9]", ".DS_Store"))
    films = set()
    for part in media.rglob("*.mp4.part[0-9][0-9][0-9]"):
        films.add(part.with_name(CHUNK.fullmatch(part.name).group(1)))
    for film in sorted(films):
        parts = video_parts(film, media)
        if not parts or film.exists():
            raise ValueError(f"Invalid split film: {film.relative_to(ROOT)}")
        with (destination / film.relative_to(ROOT)).open("wb") as output:
            for part in parts:
                with part.open("rb") as source:
                    shutil.copyfileobj(source, output, length=1024 * 1024)

    (destination / MARKER).write_text("Generated by export.py\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-path", default="/", help="URL path where the site will be hosted")
    options = parser.parse_args()
    if not re.fullmatch(r"/(?:[A-Za-z0-9._-]+/?)?", options.base_path):
        parser.error("base path should be / or a single project path")
    base_path = options.base_path.rstrip("/") + "/"
    destination = ROOT / "dist"
    if destination.is_symlink() or (destination.exists() and not (destination / MARKER).is_file()):
        raise SystemExit("dist already exists. Move it aside before running the first export.")

    with tempfile.TemporaryDirectory(prefix=".studio-export-", dir=ROOT.parent) as temp:
        temp = Path(temp)
        new, previous = temp / "new", temp / "previous"
        build(new, base_path)
        if destination.exists():
            destination.rename(previous)
        try:
            new.rename(destination)
        except OSError:
            if previous.exists():
                previous.rename(destination)
            raise
    print(f"Static site saved to {destination}")


if __name__ == "__main__":
    main()
